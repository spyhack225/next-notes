"""Generate native metadata from the same compact evidence used by the website."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
models=json.loads((ROOT/'shared/asr-models.json').read_text())
app_latency={r['id']:r['languages'] for r in json.loads((ROOT/'shared/asr-app-latency.json').read_text())}
cases={'parakeet-v3':'parakeet','qwen-06b':'qwenSmall','qwen-17b':'qwenLarge'}
lines=['// Generated by Scripts/generate_asr_catalog.py; app latency and separate earlier accuracy evidence.','import Foundation','enum ASRMeasuredModels {','    static let rows: [ASRModelInfo] = [']
for r in models:
 def metric(language):
  accuracy=r['languages'].get(language)
  live=app_latency[r['id']].get(language)
  m={**live,'wordAccuracy':accuracy['wordAccuracy']} if live and accuracy else None
  return '.init(firstMS: %.6f, finalMS: %.6f, wordAccuracy: %.6f)'%(m['firstMs'],m['finalMs'],m['wordAccuracy']) if m else 'nil'
 lines.append('        .init(choice: .%s, bytes: %d, english: %s, french: %s),'%(cases.get(r['id'],r['id']),r['bytes'],metric('en'),metric('fr')))
lines+=['    ]','}']
(ROOT/'Sources/NextNotes/Transcription/ASRMeasuredModels.swift').write_text('\n'.join(lines)+'\n')
assets=json.loads((ROOT/'shared/asr-artifacts.json').read_text())
lines=['// Generated by Scripts/generate_asr_catalog.py; pinned model artifacts.','import Foundation','enum ASRArtifacts {','    static func files(_ choice: SpeechEngineChoice) -> [ModelSpec] {','        switch choice {']
for n,specs in assets.items():
 lines.append(f'        case .{cases.get(n,n)}: return [')
 for s in specs:lines.append(f'            .init(displayName: choice.displayName, fileName: {json.dumps(s["path"])}, url: URL(string: {json.dumps(s["url"])})!, expectedBytes: {s["bytes"]}, expectedSHA256: "{s["sha256"]}"),')
 lines.append('        ]')
lines+=['        default: return []','        }','    }','}']
(ROOT/'Sources/NextNotes/Transcription/ASRArtifacts.swift').write_text('\n'.join(lines)+'\n')
